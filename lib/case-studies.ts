/** 按 slug 取词条；未命中返回 undefined，调用方负责 notFound() */
export function getCaseStudy(slug: string): CaseStudyEntry | undefined {
  return CASE_STUDIES.find((c) => c.slug === slug);
}

/** 全部 slug，供 generateStaticParams 与 sitemap 共用 */
export function getAllCaseStudySlugs(): string[] {
  return CASE_STUDIES.map((c) => c.slug);
}

/**
 * 首页案例卡片来自 Supabase cases 表（字段是 client/problem/solution），
 * 没有 slug。这里按语义把旧数据映射到对应词条，保证「点卡片=看详情」不串台。
 */
export function slugForLegacyCase(c: {
  client: string;
  problem: string;
  solution: string;
}): string {
  const text = `${c.client}${c.problem}${c.solution}`;
  if (/车灯|退货|装不上|适配/.test(text)) return CASE_STUDIES[0].slug;
  if (/毛利|亏损|汇率|折算|佣金|制动|改装/.test(text)) return CASE_STUDIES[1].slug;
  return CASE_STUDIES[2].slug; // 库存 / 滞销 / 选品 / 周转
}
